export function ChangeRequestDetailPage({id}:{id:string}){
  const{user}=useAuth();
  const{navigate}=useRouter();
  const[loading,setLoading]=useState(true);
  const[notFound,setNotFound]=useState(false);
  const[cr,setCr]=useState<any|null>(null);
  const[project,setProject]=useState<any|null>(null);
  const[crNumber,setCrNumber]=useState(0);
  const[comments,setComments]=useState<any[]>([]);
  const[commentText,setCommentText]=useState('');
  const[saving,setSaving]=useState(false);
  const[activeSteps,setActiveSteps]=useState<any[]>([]);
  const[activeFindings,setActiveFindings]=useState<any[]>([]);
  const[stepsLoading,setStepsLoading]=useState(false);
  const[previous,setPrevious]=useState<any[]>([]);
  const[trendPoints,setTrendPoints]=useState<any[]>([]);
  const[aiData,setAiData]=useState<any|null>(null);
  const[aiLoading,setAiLoading]=useState(false);
  const[aiUnavailable,setAiUnavailable]=useState('');
  const generatedRef=useRef<string>('');

  const load=useCallback(async()=>{
    setLoading(true);setNotFound(false);
    const{data:crRow}=await supabase.from('change_requests').select('*').eq('id',id).single();
    if(!crRow){setNotFound(true);setLoading(false);return;}
    setCr(crRow);

    const[{data:proj},{data:cm},{data:prev},{data:trend}]=await Promise.all([
      supabase.from('projects').select('*').eq('id',crRow.project_id).single(),
      supabase.from('change_request_comments').select('*').eq('change_request_id',id).order('created_at'),
      supabase.from('change_requests').select('*').eq('project_id',crRow.project_id).neq('id',id).order('created_at',{ascending:false}).limit(5),
      supabase.from('validations').select('risk_score,completed_at').eq('project_id',crRow.project_id).eq('status','completed').order('completed_at',{ascending:false}).limit(8),
    ]);
    setProject(proj||null);
    setComments(cm??[]);
    setPrevious(prev??[]);
    setTrendPoints((trend??[]).slice().reverse());

    const{count}=await supabase.from('change_requests').select('id',{count:'exact',head:true}).eq('workspace_id',crRow.workspace_id).lte('created_at',crRow.created_at);
    setCrNumber(count||1);

    if(crRow.validation_id){
      setStepsLoading(true);
      const[{data:steps},{data:finds}]=await Promise.all([
        supabase.from('validation_steps').select('*').eq('validation_id',crRow.validation_id).order('step_index'),
        supabase.from('findings').select('*').eq('validation_id',crRow.validation_id).order('severity'),
      ]);
      setActiveSteps(steps??[]);setActiveFindings(finds??[]);
      setStepsLoading(false);
    }else{
      setActiveSteps([]);setActiveFindings([]);
    }

    // If this record already carries persisted AI content (from a prior visit,
    // once the ai_* columns exist), use it and skip regenerating.
    if(crRow.ai_generated_at){
      setAiData({summary:crRow.ai_summary,impact:crRow.ai_impact||[],risk_contributors:crRow.ai_risk_contributors||[],reviewer_comments:crRow.ai_reviewer_comments||[],rollback:crRow.ai_rollback||{}});
    }
    setLoading(false);
  },[id]);
  useEffect(()=>{load();},[load]);

  // Auto-generate the AI review once real evidence has loaded, exactly once
  // per change request — this is what makes opening a freshly-generated
  // change request feel like it's already been reviewed.
  useEffect(()=>{
    if(!cr||loading||stepsLoading)return;
    if(cr.ai_generated_at)return; // already have persisted content
    if(generatedRef.current===cr.id)return;
    generatedRef.current=cr.id;
    runReview();
    // eslint-disable-next-line
  },[cr,loading,stepsLoading]);

  const runReview=async()=>{
    if(!cr)return;
    setAiLoading(true);setAiUnavailable('');
    const evidence={
      changeRequest:{title:cr.title,environment:cr.environment,riskLevel:cr.risk_level,status:cr.status,scope:cr.scope,summary:cr.summary,riskAssessment:cr.risk_assessment,rollbackPlan:cr.rollback_plan,scheduledStart:cr.scheduled_start,scheduledEnd:cr.scheduled_end,approverName:cr.approver_name,approverEmail:cr.approver_email},
      project:project?{name:project.name,branch:project.git_branch,language:project.language,framework:project.framework}:null,
      validation:cr.validation_snapshot&&Object.keys(cr.validation_snapshot).length?cr.validation_snapshot:null,
      findings:activeFindings.map((f:any)=>({category:f.category,severity:f.severity,title:f.title,file:f.file_path,recommendation:f.recommendation,status:f.status})),
      validationSteps:activeSteps.map((s:any)=>({name:s.name,status:s.status,detail:s.detail})),
      previousChangeRequestsForThisProject:previous.map((h:any)=>({title:h.title,riskLevel:h.risk_level,status:h.status,environment:h.environment,createdAt:h.created_at,decidedAt:h.decided_at,decisionNote:h.decision_note,rollbackRequired:h.status==='rolled_back'})),
    };
    const res=await generateDeploymentReview(evidence);
    if(!res.ok){setAiUnavailable(res.error||'AI insights are unavailable right now.');setAiLoading(false);return;}
    setAiData(res.data);
    setAiLoading(false);
    // Best-effort persistence — silently ignored if the ai_* columns (or the
    // rolled_back status value) don't exist in this database yet.
    supabase.from('change_requests').update({
      ai_summary:res.data.summary,ai_impact:res.data.impact,ai_risk_contributors:res.data.risk_contributors,
      ai_reviewer_comments:res.data.reviewer_comments,ai_rollback:res.data.rollback,ai_generated_at:new Date().toISOString(),
    }).eq('id',cr.id).then(()=>{});
  };

  const saveField=async(patch:Record<string,any>)=>{
    if(!cr)return;
    setSaving(true);
    const{data,error}=await supabase.from('change_requests').update({...patch,revision:(cr.revision||1)+1}).eq('id',cr.id).select().single();
    if(data)setCr(data);
    else if(error){
      // revision column may not exist yet on this database — retry without it
      const retry=await supabase.from('change_requests').update(patch).eq('id',cr.id).select().single();
      if(retry.data)setCr(retry.data);
    }
    setSaving(false);
  };
  const decide=async(status:'approved'|'rejected',note:string)=>{
    await saveField({status,decided_by:user?.id||null,decided_at:new Date().toISOString(),decision_note:note||null});
  };
  const markOutcome=async(status:'completed'|'rolled_back')=>{
    await saveField({status});
  };
  const addComment=async()=>{
    if(!cr||!commentText.trim())return;
    const{data}=await supabase.from('change_request_comments').insert({change_request_id:cr.id,workspace_id:cr.workspace_id,body:commentText.trim()}).select().single();
    if(data){setComments(c=>[...c,data]);setCommentText('');}
  };

  if(loading)return<div className="flex justify-center py-24"><Spinner size={28}/></div>;
  if(notFound||!cr)return<div className="max-w-2xl">
    <EmptyState icon={<GitBranch size={22}/>} title="Change request not found" description="It may have been deleted, or you don't have access to it." action={<button onClick={()=>navigate('/change-management')} className="btn-primary">Back to Change Management</button>}/>
  </div>;

  const crView={...cr,...(aiData?{ai_summary:aiData.summary,ai_impact:aiData.impact,ai_risk_contributors:aiData.risk_contributors,ai_reviewer_comments:aiData.reviewer_comments,ai_rollback:aiData.rollback,ai_generated_at:cr.ai_generated_at||new Date().toISOString()}:{})};
  const projectName=project?.name||'—';
  const readiness=cr.validation_snapshot&&typeof cr.validation_snapshot.risk_score==='number'?Math.max(0,100-cr.validation_snapshot.risk_score):null;
  const relatedFindings=activeFindings.filter((f:any)=>f.status==='open'&&(f.severity==='critical'||f.severity==='high'));

  return<div className="max-w-4xl">
    <button onClick={()=>navigate('/change-management')} className="mb-4 inline-flex items-center gap-1 text-xs font-medium text-gray-500 hover:text-navy-700"><ChevronLeft size={14}/>Back to change requests</button>

    {/* Header */}
    <div className="card mb-5">
      <div className="flex flex-wrap items-start justify-between gap-4">
        <div>
          <p className="text-2xs font-semibold uppercase tracking-wide text-brand-600">CR-{crNumber}</p>
          <h1 className="mt-0.5 text-lg font-bold text-navy-900">{cr.title}</h1>
          <p className="mt-1 flex flex-wrap items-center gap-x-1.5 gap-y-0.5 text-xs text-gray-500">
            <span className="font-medium text-navy-700">{projectName}</span>·<span>{cr.environment}</span>·<span>v{cr.revision||1}</span>·<span>requested {timeAgo(cr.created_at)}</span>
          </p>
        </div>
        <div className="flex flex-wrap items-center gap-2">
          <span className={`chip ${RISK_CLS[cr.risk_level]||RISK_CLS.unknown}`}>{(cr.risk_level||'unknown').toUpperCase()} risk</span>
          <span className={`chip ${STATUS_CLS[cr.status]||STATUS_CLS.draft}`}>{STATUS_LABEL[cr.status]||cr.status}</span>
        </div>
      </div>
      <div className="mt-4 grid grid-cols-2 gap-3 border-t border-gray-100 pt-4 sm:grid-cols-4">
        <div><p className="text-2xs text-gray-400">Deployment window</p><p className="mt-0.5 text-xs font-medium text-navy-800">{cr.scheduled_start?new Date(cr.scheduled_start).toLocaleDateString():'Not scheduled'}</p></div>
        <div><p className="text-2xs text-gray-400">Risk score</p><p className="mt-0.5 text-xs font-medium text-navy-800">{cr.validation_snapshot?.risk_score??'—'}/100</p></div>
        <div><p className="text-2xs text-gray-400">Deployment readiness</p><p className="mt-0.5 text-xs font-medium text-navy-800">{readiness===null?'—':`${readiness}%`}</p></div>
        <div><p className="text-2xs text-gray-400">Status</p><p className="mt-0.5 text-xs font-medium text-navy-800">{STATUS_LABEL[cr.status]||cr.status}</p></div>
      </div>
    </div>

    <div className="space-y-5">
      <ExecutiveSummaryCard cr={crView} onGenerate={runReview} loading={aiLoading} unavailable={aiUnavailable}/>

      <div className="grid gap-5 lg:grid-cols-2">
        <RiskAssessmentCard cr={crView} trendPoints={trendPoints}/>
        <ReadinessChecklist cr={cr} steps={activeSteps} stepsLoading={stepsLoading}/>
      </div>

      <div className="grid gap-5 lg:grid-cols-2">
        <ImpactAnalysisCard cr={crView} onGenerate={runReview} loading={aiLoading}/>
        <WhatsChangingCard steps={activeSteps} findings={activeFindings}/>
      </div>

      <div className="grid gap-5 lg:grid-cols-2">
        <DeploymentTimeline cr={cr}/>
        <PreviousChangesCard items={previous} loading={false} title="Similar previous deployments"/>
      </div>

      <RollbackPlanCard cr={crView} onGenerate={runReview} loading={aiLoading}/>
      <ReviewerCommentsCard cr={crView} onGenerate={runReview} loading={aiLoading}/>

      {/* Approval */}
      <div className="card">
        <p className="mb-3.5 text-sm font-semibold text-navy-900">Approval</p>
        <div className="grid gap-4 sm:grid-cols-2">
          <div>
            <label className="label">Approver name</label>
            <input className="input" defaultValue={cr.approver_name||''} placeholder="e.g. VP Engineering" onBlur={(e)=>saveField({approver_name:e.target.value||null})}/>
          </div>
          <div>
            <label className="label">Approver email</label>
            <input className="input" defaultValue={cr.approver_email||''} placeholder="approver@company.com" onBlur={(e)=>saveField({approver_email:e.target.value||null})}/>
          </div>
          <div>
            <label className="label flex items-center gap-1"><Calendar size={12}/>Scheduled start</label>
            <input type="datetime-local" className="input" defaultValue={cr.scheduled_start?.slice(0,16)||''} onBlur={(e)=>saveField({scheduled_start:e.target.value||null})}/>
          </div>
          <div>
            <label className="label flex items-center gap-1"><Calendar size={12}/>Scheduled end</label>
            <input type="datetime-local" className="input" defaultValue={cr.scheduled_end?.slice(0,16)||''} onBlur={(e)=>saveField({scheduled_end:e.target.value||null})}/>
          </div>
        </div>

        {cr.status==='pending_approval'&&<div className="mt-4"><DecisionBar onDecide={decide}/></div>}
        {cr.decided_at&&(
          <div className="mt-4 rounded-xl border border-[#18181b] p-3 text-xs text-gray-600">
            {STATUS_LABEL[cr.status]} on {new Date(cr.decided_at).toLocaleString()}{cr.decision_note?` — "${cr.decision_note}"`:''}
          </div>
        )}
        {cr.status==='approved'&&(
          <div className="mt-4 flex flex-wrap items-center gap-2 rounded-xl border border-green-200 bg-green-50 p-3.5">
            <p className="mr-auto text-xs font-medium text-green-700">Approved — once it ships, record the real outcome.</p>
            <button onClick={()=>markOutcome('completed')} className="btn-secondary text-xs flex items-center gap-1.5"><CheckCircle2 size={12}/>Mark completed</button>
            <button onClick={()=>markOutcome('rolled_back')} className="btn-secondary text-xs flex items-center gap-1.5"><XCircle size={12}/>Mark rolled back</button>
          </div>
        )}
        <div className="mt-4 flex flex-wrap items-center gap-2 border-t border-gray-100 pt-4">
          {cr.status==='draft'&&(
            <button onClick={()=>saveField({status:'pending_approval'})} className="btn-brand text-xs flex items-center gap-1.5"><Send size={12}/>Send for approval</button>
          )}
        </div>
      </div>

      <ExportToolbar
        summaryText={crView.ai_summary||cr.summary||''}
        onExportPdf={()=>downloadChangePlanPdf(crView,projectName,crNumber,relatedFindings)}
        onExportMarkdown={()=>downloadMarkdown(`cr-${crNumber}-${(cr.title||'change-request').replace(/[^a-z0-9]+/gi,'-').toLowerCase()}.md`,buildMarkdown(crView,projectName,crNumber,relatedFindings))}
      />

      {/* Change details (editable record) */}
      <div className="card">
        <p className="mb-3.5 text-sm font-semibold text-navy-900">Change details</p>
        <div className="space-y-5">
          <Field label="Summary" value={cr.summary} onSave={(v)=>saveField({summary:v})} disabled={saving}/>
          <div>
            <label className="label">Scope of change</label>
            <div className="flex flex-wrap gap-1.5">
              {(cr.scope||[]).length===0&&<span className="text-xs text-gray-400">General</span>}
              {(cr.scope||[]).map((s:string)=><span key={s} className="chip bg-gray-100 text-gray-600 border border-[#18181b]">{s}</span>)}
            </div>
          </div>
          <Field label="Risk assessment (editable record)" value={cr.risk_assessment} onSave={(v)=>saveField({risk_assessment:v})} multiline disabled={saving}/>
          <Field label="Rollback plan (editable record)" value={cr.rollback_plan} onSave={(v)=>saveField({rollback_plan:v})} multiline disabled={saving}/>
        </div>
      </div>

      {/* Discussion */}
      <div className="card">
        <p className="mb-3 flex items-center gap-1.5 text-sm font-semibold text-navy-900"><MessageSquare size={14}/>Discussion</p>
        <div className="space-y-3">
          {comments.length===0&&<p className="text-xs text-gray-400">No comments yet — coordinate the change with your team here.</p>}
          {comments.map((c:any)=>(
            <div key={c.id} className="rounded-xl bg-gray-50 px-3.5 py-2.5">
              <p className="text-sm text-navy-800">{c.body}</p>
              <p className="mt-1 text-[11px] text-gray-400">{timeAgo(c.created_at)}</p>
            </div>
          ))}
        </div>
        <div className="mt-3 flex gap-2">
          <input value={commentText} onChange={(e)=>setCommentText(e.target.value)} onKeyDown={(e)=>{if(e.key==='Enter')addComment();}} className="input" placeholder="Add a note for your team…"/>
          <button onClick={addComment} className="btn-secondary text-xs shrink-0">Post</button>
        </div>
      </div>
    </div>
  </div>;
}

function Field({label,value,onSave,multiline,disabled}:{label:string;value:string;onSave:(v:string)=>void;multiline?:boolean;disabled?:boolean}){
  const[v,setV]=useState(value||'');
  useEffect(()=>{setV(value||'');},[value]);
  const Tag:any=multiline?'textarea':'input';
  return<div>
    <label className="label">{label}</label>
    <Tag className="input" rows={multiline?5:undefined} value={v} disabled={disabled}
      onChange={(e:any)=>setV(e.target.value)} onBlur={()=>{if(v!==value)onSave(v);}}/>
  </div>;
}

function DecisionBar({onDecide}:{onDecide:(status:'approved'|'rejected',note:string)=>void}){
  const[note,setNote]=useState('');
  return<div className="rounded-xl border border-amber-200 bg-amber-50 p-3.5">
    <p className="mb-2 text-xs font-semibold text-amber-700">This change is awaiting a decision.</p>
    <input value={note} onChange={(e)=>setNote(e.target.value)} placeholder="Decision note (optional)" className="input mb-2"/>
    <div className="flex gap-2">
      <button onClick={()=>onDecide('approved',note)} className="btn-brand text-xs flex items-center gap-1.5"><CheckCircle2 size={12}/>Approve</button>
      <button onClick={()=>onDecide('rejected',note)} className="btn-secondary text-xs flex items-center gap-1.5"><XCircle size={12}/>Reject</button>
    </div>
  </div>;
}
