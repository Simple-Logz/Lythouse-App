// ── AI Deployment Review Center ─────────────────────────────────────────────
// The page a change request lands on right after it's generated. This is
// the heart of the feature: instead of a form dump, it reads like a senior
// engineer already reviewed the deployment — executive summary, impact
// analysis, a real risk dashboard with trend, a dynamic readiness checklist,
// a DevOps-style rollback runbook, reviewer notes, a plain-English "what's
// changing", a timeline, similar past deployments, and the approval flow.
//
// AI content is generated client-side against the already-deployed ai-chat
// Edge Function (see ../workspace/changeAI.ts) — grounded ONLY in this
// change request's real validation/findings/history, exactly like every
// other AI feature in this app. It's generated fresh on load and cached in
// component state; the page also makes a best-effort attempt to persist it
// back onto the change_requests row (ai_summary / ai_impact / etc. columns)
// so a future visit can skip regenerating — but never depends on that
// persistence succeeding, so the page works whether or not that schema
// migration has been applied yet.

function riskFromCounts(v:any):string{
  if(!v)return'unknown';
  if((v.critical_count||0)>0)return'critical';
  if((v.high_count||0)>0)return'high';
  if((v.medium_count||0)>0)return'medium';
  return'low';
}

function buildMarkdown(cr:any,projectName:string,crNumber:number,findings:any[]):string{
  const L:string[]=[];
  L.push(`# ${cr.title||'Change request'}`,'');
  L.push(`**Change request:** CR-${crNumber}  `);
  L.push(`**Project:** ${projectName}  `);
  L.push(`**Environment:** ${cr.environment}  `);
  L.push(`**Risk level:** ${(cr.risk_level||'unknown').toUpperCase()}  `);
  L.push(`**Status:** ${STATUS_LABEL[cr.status]||cr.status}  `);
  L.push(`**Version:** v${cr.revision||1}  `);
  if(cr.scheduled_start)L.push(`**Deployment window:** ${new Date(cr.scheduled_start).toLocaleString()} → ${cr.scheduled_end?new Date(cr.scheduled_end).toLocaleString():'—'}  `);
  L.push('');
  if(cr.ai_summary)L.push('## AI Executive Summary','',cr.ai_summary,'');
  L.push('## Summary','',cr.summary||'—','');
  L.push('## Scope of Change','',(cr.scope&&cr.scope.length?cr.scope:['General']).map((s:string)=>`- ${s}`).join('\n'),'');
  if(cr.ai_impact&&cr.ai_impact.length)L.push('## Impact Analysis','',cr.ai_impact.map((i:any)=>`- **${i.component}** — ${i.reason}`).join('\n'),'');
  L.push('## Risk Assessment','',cr.risk_assessment||'—','');
  L.push('## Rollback Plan','',cr.rollback_plan||'—','');
  if(cr.ai_rollback&&cr.ai_rollback.steps&&cr.ai_rollback.steps.length){
    const rb=cr.ai_rollback;
    L.push('### AI-Drafted Rollback Detail','',rb.steps.map((s:string,i:number)=>`${i+1}. ${s}`).join('\n'));
    if(rb.estimated_duration)L.push(`\n**Estimated duration:** ${rb.estimated_duration}`);
    if(rb.dependencies?.length)L.push(`**Dependencies:** ${rb.dependencies.join(', ')}`);
    if(rb.approvals_required?.length)L.push(`**Approvals required:** ${rb.approvals_required.join(', ')}`);
    L.push('');
  }
  if(cr.ai_reviewer_comments&&cr.ai_reviewer_comments.length)L.push('## AI Reviewer Comments','',cr.ai_reviewer_comments.map((c:string)=>`- ${c}`).join('\n'),'');
  if(findings&&findings.length)L.push('## Open Critical / High Findings','',findings.map((f:any)=>`- [${f.severity.toUpperCase()}] ${f.title}${f.recommendation?` — ${f.recommendation}`:''}`).join('\n'),'');
  L.push('## Approval','',`Sent to: ${cr.approver_name||'—'}${cr.approver_email?` (${cr.approver_email})`:''}`,`Decision: ${cr.decided_at?`${STATUS_LABEL[cr.status]||cr.status} on ${new Date(cr.decided_at).toLocaleString()}`:'Not yet decided'}`,'');
  L.push('---',`*Generated by LytHouse${cr.ai_summary?' AI':''} on ${new Date().toLocaleString()}*`);
  return L.join('\n');
}
